/* ---- the version is read, never written -----------------------------
   Every artefact this script emits used to carry a hand-typed version:
   the two .d.ts headers and the CLI banner each had their own literal,
   which is how the published tarball ended up announcing a version two
   releases behind its own package.json. See external audit N-17, and
   the CLI half of N-18, for the measured numbers -- they are
   deliberately not repeated here, because a literal version in this
   file is the very thing the coherence check refuses.

   The authoritative constant is the `version:` key on the NAC export
   at the bottom of js/nac.js -- the same one scripts/build-integrity.mjs
   reads and SPEC.md sec 9 declares normative. Bumping a version means
   editing js/nac.js and running this build. Nothing else.

   scripts/check-version-coherence.mjs refuses a literal version in this
   file, so the hard-coding cannot come back by hand.
   -------------------------------------------------------------------- */

const NAC_SRC_PATH = path.join(SRC_DIR, 'nac.js');
if (!fs.existsSync(NAC_SRC_PATH)) {
  console.error('build: cannot find the runtime source at ' + NAC_SRC_PATH);
  console.error('build: refusing to emit artefacts with no version to stamp them with.');
  process.exit(1);
}
const NAC_SRC = fs.readFileSync(NAC_SRC_PATH, 'utf8');

function readConstant(label, rx) {
  const m = NAC_SRC.match(rx);
  if (!m) {
    console.error('build: cannot read ' + label + ' from js/nac.js.');
    console.error('build: refusing to emit artefacts that would misdeclare their version.');
    process.exit(1);
  }
  return m[1];
}

