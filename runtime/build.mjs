function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}
function read(p) {
  return fs.readFileSync(p, 'utf8');
}
function write(p, content) {
  ensureDir(path.dirname(p));
  fs.writeFileSync(p, content);
}

